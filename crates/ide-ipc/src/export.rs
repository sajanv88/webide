//! Generates the contracts from the command list in `commands.rs`:
//!
//! - `packages/contracts/src/generated/*.ts`: every DTO (ts-rs), `commands.ts`
//!   (the `CommandMap`), and `index.ts`.
//! - `apps/desktop/src-tauri/ipc_commands.rs`: the command names, included by
//!   `build.rs`, which gives each an `allow-*` permission.
//! - `apps/desktop/src-tauri/permissions/ipc-commands.toml`: one permission set
//!   with all of them, which the main window's capability grants.
//!
//! Run with `pnpm contracts:generate`. `cargo xtask check-contracts` runs the
//! same export into a temporary folder and fails if anything differs.

use std::collections::BTreeSet;
use std::fs;
use std::path::{Path, PathBuf};

use ts_rs::{Config, ExportError, TS, TypeVisitor};

use crate::commands::{COMMAND_NAMES, signatures};
use crate::dto::BackendEventDto;
use crate::error::IpcError;

const HEADER: &str = "// Generated by `pnpm contracts:generate` from crates/ide-ipc. Do not edit.";

/// A command's TypeScript argument and output types.
pub(crate) struct Signature {
    name: &'static str,
    args: fn(&Config) -> String,
    output: fn(&Config) -> String,
    export: fn(&Config) -> Result<(), ExportError>,
}

impl Signature {
    pub(crate) fn of<A: TS + 'static, O: TS + 'static>(name: &'static str) -> Self {
        Self {
            name,
            args: A::name,
            output: O::name,
            export: |cfg| {
                export_tree::<A>(cfg)?;
                export_tree::<O>(cfg)
            },
        }
    }
}

/// Exports `T` with its dependencies; for a built-in like `Vec<T>` or
/// `Option<T>`, which has no file of its own, exports what it contains.
fn export_tree<T: TS + 'static + ?Sized>(cfg: &Config) -> Result<(), ExportError> {
    if T::output_path().is_some() {
        return T::export_all(cfg);
    }
    struct Visit<'a> {
        cfg: &'a Config,
        result: Result<(), ExportError>,
    }
    impl TypeVisitor for Visit<'_> {
        fn visit<U: TS + 'static + ?Sized>(&mut self) {
            if self.result.is_ok() {
                self.result = export_tree::<U>(self.cfg);
            }
        }
    }
    let mut visit = Visit {
        cfg,
        result: Ok(()),
    };
    T::visit_generics(&mut visit);
    T::visit_dependencies(&mut visit);
    visit.result
}

pub(crate) fn export(ts_dir: &Path, tauri_dir: &Path) -> Result<(), String> {
    fs::create_dir_all(ts_dir).map_err(|e| format!("create {}: {e}", ts_dir.display()))?;
    // Remove what a previous run generated, so a deleted DTO doesn't linger.
    for entry in fs::read_dir(ts_dir).map_err(|e| e.to_string())?.flatten() {
        if entry.path().extension().is_some_and(|ext| ext == "ts") {
            fs::remove_file(entry.path()).map_err(|e| e.to_string())?;
        }
    }

    let cfg = Config::new().with_out_dir(ts_dir).with_large_int("number");
    IpcError::export_all(&cfg).map_err(|e| e.to_string())?;
    // Not a command's argument or result: it arrives over the events channel.
    BackendEventDto::export_all(&cfg).map_err(|e| e.to_string())?;
    let signatures = signatures();
    for signature in &signatures {
        (signature.export)(&cfg).map_err(|e| format!("{}: {e}", signature.name))?;
    }

    let types = exported_types(ts_dir)?;
    write(
        &ts_dir.join("commands.ts"),
        &commands_ts(&cfg, &signatures, &types),
    )?;
    write(&ts_dir.join("index.ts"), &index_ts(&types))?;

    fs::create_dir_all(tauri_dir).map_err(|e| format!("create {}: {e}", tauri_dir.display()))?;
    write(&tauri_dir.join("ipc_commands.rs"), &ipc_commands_rs())?;
    let permissions = tauri_dir.join("permissions");
    fs::create_dir_all(&permissions).map_err(|e| e.to_string())?;
    write(
        &permissions.join("ipc-commands.toml"),
        &permission_set_toml(),
    )?;
    Ok(())
}

fn exported_types(dir: &Path) -> Result<BTreeSet<String>, String> {
    let mut types = BTreeSet::new();
    for entry in fs::read_dir(dir).map_err(|e| e.to_string())?.flatten() {
        let path = entry.path();
        if path.extension().is_some_and(|ext| ext == "ts")
            && let Some(stem) = path.file_stem().and_then(|stem| stem.to_str())
        {
            types.insert(stem.to_owned());
        }
    }
    Ok(types)
}

fn commands_ts(cfg: &Config, signatures: &[Signature], types: &BTreeSet<String>) -> String {
    let rows: Vec<(String, String, String)> = signatures
        .iter()
        .map(|s| (s.name.to_owned(), (s.args)(cfg), (s.output)(cfg)))
        .collect();
    let used: BTreeSet<&str> = rows
        .iter()
        .flat_map(|(_, args, output)| [args.as_str(), output.as_str()])
        .flat_map(|text| text.split(|c: char| !c.is_ascii_alphanumeric() && c != '_'))
        .filter(|word| types.contains(*word))
        .collect();

    let mut out = format!("{HEADER}\n\n");
    for name in &used {
        out.push_str(&format!("import type {{ {name} }} from \"./{name}\";\n"));
    }
    out.push_str(
        "\n/** Every IPC command: what it takes (`null` for nothing) and what it resolves to. */\n",
    );
    out.push_str("export interface CommandMap {\n");
    for (name, args, output) in &rows {
        out.push_str(&format!(
            "  {name}: {{ args: {args}; output: {output} }};\n"
        ));
    }
    out.push_str("}\n\nexport type CommandName = keyof CommandMap;\n");
    out
}

/// Re-exports every DTO file and `commands.ts`.
fn index_ts(types: &BTreeSet<String>) -> String {
    let mut out = format!("{HEADER}\n\n");
    for name in types
        .iter()
        .filter(|name| *name != "index" && *name != "commands")
    {
        out.push_str(&format!("export type * from \"./{name}\";\n"));
    }
    out.push_str("export type * from \"./commands\";\n");
    out
}

fn ipc_commands_rs() -> String {
    let mut out = format!(
        "{HEADER}\n\n/// Every command `ide-ipc` registers.\nconst IPC_COMMANDS: &[&str] = &[\n"
    );
    for name in COMMAND_NAMES {
        out.push_str(&format!("    \"{name}\",\n"));
    }
    out.push_str("];\n");
    out
}

fn permission_set_toml() -> String {
    let mut out = format!(
        "{}\n\n[[set]]\nidentifier = \"ipc-commands\"\ndescription = \"Allows every command registered by ide-ipc, and nothing else.\"\npermissions = [\n",
        HEADER.replacen("//", "#", 1)
    );
    for name in COMMAND_NAMES {
        out.push_str(&format!("  \"allow-{}\",\n", name.replace('_', "-")));
    }
    out.push_str("]\n");
    out
}

fn write(path: &Path, contents: &str) -> Result<(), String> {
    fs::write(path, contents).map_err(|e| format!("write {}: {e}", path.display()))
}

fn dir_from_env(name: &str) -> PathBuf {
    match std::env::var_os(name) {
        Some(dir) => PathBuf::from(dir),
        None => panic!("{name} is not set; run `pnpm contracts:generate` (see .cargo/config.toml)"),
    }
}

#[test]
#[ignore = "writes the contracts into the repo; run with `pnpm contracts:generate`"]
fn export_bindings() {
    let ts_dir = dir_from_env("IDE_CONTRACTS_TS_DIR");
    let tauri_dir = dir_from_env("IDE_CONTRACTS_TAURI_DIR");
    if let Err(error) = export(&ts_dir, &tauri_dir) {
        panic!("export failed: {error}");
    }
}

#[test]
fn every_command_has_a_signature() {
    let names: Vec<_> = signatures().iter().map(|s| s.name).collect();
    assert_eq!(names, COMMAND_NAMES);
}
